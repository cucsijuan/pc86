#!/usr/bin/env python3
"""
Generates src/font_cp437.c (8x16 and 8x8 CP437 fonts) from the unscii fonts
by viznut, which are public domain / CC0: https://github.com/viznut/unscii
Only unscii-16.hex and unscii-8.hex are used; the "-full" variants contain
GPL Unifont glyphs and must not be used.

Usage: python3 tools/gen_font.py path/to/unscii/fontfiles > src/font_cp437.c

Four CP437 characters are missing from unscii and are derived or drawn here:
  0x0F (sun), 0x7F (house): drawn below
  0xA9 (reversed not sign): mirror of U+00AC
  0xF9 (bullet operator):   U+00B7 middle dot
"""
import os
import sys

LOW = "\u0000☺☻♥♦♣♠•◘○◙♂♀♪♫☼►◄↕‼¶§▬↨↑↓→←∟↔▲▼"


def cp437_to_unicode(i):
    if i == 0:
        return 0x20
    if i < 32:
        return ord(LOW[i])
    if i == 0x7F:
        return 0x2302
    return ord(bytes([i]).decode("cp437"))


# Hand-drawn glyphs ('#' = pixel on)
SUN16 = ["........", "........", "...#....", "#..#..#.", ".#...#..", "..###...", ".#####..", "###.###.",
         ".#####..", "..###...", ".#...#..", "#..#..#.", "...#....", "........", "........", "........"]
HOUSE16 = ["........", "........", "........", "........", "...#....", "..#.#...", ".#...#..", "#.....#.",
           "#.....#.", "#.....#.", "#.....#.", "#######.", "........", "........", "........", "........"]
SUN8 = ["...#....", "#..#..#.", "..###...", "###.###.", "..###...", "#..#..#.", "...#....", "........"]
HOUSE8 = ["...#....", "..#.#...", ".#...#..", "#.....#.", "#.....#.", "#######.", "........", "........"]


def drawn(rows):
    return [int(r.replace("#", "1").replace(".", "0"), 2) for r in rows]


def load(path):
    g = {}
    for line in open(path):
        k, v = line.strip().split(":")
        g[int(k, 16)] = [int(v[i:i + 2], 16) for i in range(0, len(v), 2)]
    return g


def mirror(rows):
    return [int(f"{r:08b}"[::-1], 2) for r in rows]


def build(g, sun, house):
    out = []
    for i in range(256):
        if i == 0x0F:
            rows = drawn(sun)
        elif i == 0x7F:
            rows = drawn(house)
        elif i == 0xA9:
            rows = mirror(g[0x00AC])
        elif i == 0xF9:
            rows = g[0x00B7]
        else:
            rows = g[cp437_to_unicode(i)]
        out.append(rows)
    return out


def emit(name, font, h):
    print(f"const uint8_t {name}[256][{h}] = {{")
    for i, rows in enumerate(font):
        print("    {" + ", ".join(f"0x{r:02X}" for r in rows) + f"}}, /* {i:02X} */")
    print("};\n")


def main():
    d = sys.argv[1]
    f16 = build(load(os.path.join(d, "unscii-16.hex")), SUN16, HOUSE16)
    f8 = build(load(os.path.join(d, "unscii-8.hex")), SUN8, HOUSE8)
    print("/*")
    print(" * CP437 fonts, 8x16 (text mode) and 8x8 (mode 13h BIOS text).")
    print(" * Generated by tools/gen_font.py from unscii by viznut (public domain / CC0).")
    print(" * Do not edit by hand.")
    print(" */")
    print('#include "font_cp437.h"\n')
    emit("vga_font_8x16", f16, 16)
    emit("vga_font_8x8", f8, 8)


if __name__ == "__main__":
    main()
